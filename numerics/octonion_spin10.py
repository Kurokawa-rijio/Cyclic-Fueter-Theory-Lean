import numpy as np, itertools
rng = np.random.default_rng(1)

# ---- quaternions and octonions by Cayley--Dickson: (a,b)(c,d) = (ac - conj(d) b, d a + b conj(c)) ----
def qmul(p, q):
    a0,a1,a2,a3 = p; b0,b1,b2,b3 = q
    return np.array([a0*b0-a1*b1-a2*b2-a3*b3, a0*b1+a1*b0+a2*b3-a3*b2,
                     a0*b2-a1*b3+a2*b0+a3*b1, a0*b3+a1*b2-a2*b1+a3*b0])
qconj = lambda q: q*np.array([1,-1,-1,-1])
def omul(x, y):
    a,b,c,d = x[:4],x[4:],y[:4],y[4:]
    return np.concatenate([qmul(a,c)-qmul(qconj(d),b), qmul(d,a)+qmul(b,qconj(c))])
oconj = lambda x: x*np.array([1]+[-1]*7)
E = np.eye(8)
def Lmat(a): return np.array([omul(a,E[j]) for j in range(8)]).T
def Rmat(a): return np.array([omul(E[j],a) for j in range(8)]).T
def LmatQ(a): return np.array([qmul(a,np.eye(4)[j]) for j in range(4)]).T
ok = lambda b: 'OK' if b else 'FAIL'
res = {}

# 1. composition and transpose
a = rng.normal(size=8)
res['L_a^T = L_conj(a)'] = np.allclose(Lmat(a).T, Lmat(oconj(a)))
res['L_a^T L_a = |a|^2'] = np.allclose(Lmat(a).T@Lmat(a), a@a*np.eye(8)) and np.allclose(Lmat(a)@Lmat(a).T, a@a*np.eye(8))
res['R_a^T R_a = |a|^2'] = np.allclose(Rmat(a).T@Rmat(a), a@a*np.eye(8))
b = rng.normal(size=8)
res['non-associative (L_a L_b != L_ab)'] = not np.allclose(Lmat(a)@Lmat(b), Lmat(omul(a,b)))
res['alternative: L_a L_a = L_{a a}'] = np.allclose(Lmat(a)@Lmat(a), Lmat(omul(a,a)))
res['flexible: L_a R_a = R_a L_a'] = np.allclose(Lmat(a)@Rmat(a), Rmat(a)@Lmat(a))
res['L,R do not commute in general'] = not np.allclose(Lmat(a)@Rmat(b), Rmat(b)@Lmat(a))

# 2. singular-value (nullity) formula for complex a = x + i y
def sv_formula(x, y, m):
    nn = x@x + y@y; N = (x@x - y@y) + 2j*(x@y)
    d = np.sqrt(max(nn**2 - abs(N)**2, 0.0))
    return np.sort(np.concatenate([np.full(m//2, np.sqrt(nn+d)), np.full(m//2, np.sqrt(max(nn-d,0)))]))
good = True
for _ in range(50):
    x, y = rng.normal(size=8), rng.normal(size=8)
    for M in (Lmat, Rmat):
        sv = np.sort(np.linalg.svd(M(x)+1j*M(y), compute_uv=False))
        good &= np.allclose(sv, sv_formula(x, y, 8))
    xq, yq = rng.normal(size=4), rng.normal(size=4)
    good &= np.allclose(np.sort(np.linalg.svd(LmatQ(xq)+1j*LmatQ(yq), compute_uv=False)), sv_formula(xq, yq, 4))
res['singular values sigma^2 = |a|^2 +- sqrt(|a|^4-|N(a)|^2), mult m/2 (H, O left/right)'] = good
x = rng.normal(size=8); y = rng.normal(size=8); y -= (x@y)/(x@x)*x; y *= np.linalg.norm(x)/np.linalg.norm(y)
res['null complex octonion: rank L = 4, rank R = 4'] = (np.linalg.matrix_rank(Lmat(x)+1j*Lmat(y), tol=1e-9) == 4 and np.linalg.matrix_rank(Rmat(x)+1j*Rmat(y), tol=1e-9) == 4)

# 3. Lie algebras generated by left multiplications by imaginary units
def lie_dim(gens):
    basis = []
    def add(X):
        v = X.flatten(); B = np.array(basis+[v])
        if np.linalg.matrix_rank(B, tol=1e-9) > len(basis): basis.append(v); return True
        return False
    for g in gens: add(g)
    changed = True
    while changed:
        changed = False
        n = len(basis); d = int(np.sqrt(len(basis[0])))
        mats = [v.reshape(d,d) for v in basis]
        for i in range(n):
            for j in range(i+1, n):
                if add(mats[i]@mats[j]-mats[j]@mats[i]): changed = True
    return len(basis)
res['Lie algebra generated by L_{e_1..e_7} has dim 28 = so(8)'] = lie_dim([Lmat(E[i]) for i in range(1,8)]) == 28
res['Lie algebra generated by quaternion L_i,L_j,L_k has dim 3 = su(2)'] = lie_dim([LmatQ(np.eye(4)[i]) for i in range(1,4)]) == 3

# 4. slice complex structure: I = e7, J = R_I. L_z for z = s + t I is z on C_I and conj(z) on C_I^perp
I = E[7]; J = Rmat(I)
res['J = R_I squares to -1'] = np.allclose(J@J, -np.eye(8))
res['L_I commutes with J'] = np.allclose(Lmat(I)@J, J@Lmat(I))
Vplus = np.array([E[0], E[7]]).T      # C_I = span(1, I)
P = Lmat(I) - J; res['L_I = J on C_I'] = np.allclose(P@Vplus, 0)
Q = Lmat(I) + J; Vminus = E[:,1:7]; res['L_I = -J on C_I^perp (complex dim 3)'] = np.allclose(Q@Vminus, 0)
s, t = rng.normal(size=2); z = s*E[0] + t*I
res['L_z = s + t J on C_I and s - t J on C_I^perp'] = np.allclose(Lmat(z)@Vplus, (s*np.eye(8)+t*J)@Vplus) and np.allclose(Lmat(z)@Vminus, (s*np.eye(8)-t*J)@Vminus)

# 5. Spin(9) gamma matrices on O^2 = R^16 from octonions; 6. Spin(10) Weyl block
G = [np.block([[np.zeros((8,8)), Lmat(E[j])],[Lmat(E[j]).T, np.zeros((8,8))]]) for j in range(8)]
G.append(np.block([[np.eye(8), np.zeros((8,8))],[np.zeros((8,8)), -np.eye(8)]]))
res['nine real symmetric anticommuting 16x16 matrices squaring to 1'] = all(np.allclose(G[i], G[i].T) for i in range(9)) and all(np.allclose(G[i]@G[j]+G[j]@G[i], 2*(i==j)*np.eye(16)) for i in range(9) for j in range(9))
sig  = lambda v: 1j*v[0]*np.eye(16) + sum(v[k+1]*G[k] for k in range(9))
sigt = lambda v: -1j*v[0]*np.eye(16) + sum(v[k+1]*G[k] for k in range(9))
v = rng.normal(size=10) + 1j*rng.normal(size=10)
res['sigma~(v) sigma(v) = (v.v) 1 for complex v'] = np.allclose(sigt(v)@sig(v), (v@v)*np.eye(16)) and np.allclose(sig(v)@sigt(v), (v@v)*np.eye(16))
good = True
for _ in range(30):
    x, y = rng.normal(size=10), rng.normal(size=10)
    good &= np.allclose(np.sort(np.linalg.svd(sig(x+1j*y), compute_uv=False)), sv_formula(x, y, 16))
res['Spin(10) Weyl block: singular-value formula with multiplicity 8'] = good
x = rng.normal(size=10); y = rng.normal(size=10); y -= (x@y)/(x@x)*x; y *= np.linalg.norm(x)/np.linalg.norm(y)
res['null v in C^10: rank sigma(v) = 8 (nullity 8)'] = np.linalg.matrix_rank(sig(x+1j*y), tol=1e-9) == 8
# 2x2 octonionic form: sigma(v) = [[i v0 + v9, L_a],[L_a^T, i v0 - v9]] with a = (v1..v8)
vv = rng.normal(size=10); a8 = vv[1:9]
blk = np.block([[ (1j*vv[0]+vv[9])*np.eye(8), Lmat(a8)],[Lmat(a8).T, (1j*vv[0]-vv[9])*np.eye(8)]])
res['sigma(v) is the 2x2 octonionic matrix [[i v0+v9, a],[conj a, i v0-v9]]'] = np.allclose(blk, sig(vv))

# 7. weights of the 16: Cartan generators (1/2) gamma_{2k} gamma_{2k+1} in 32-dim Dirac rep
gam = []
for k in range(10):
    ek = np.zeros(10); ek[k] = 1
    gam.append(np.block([[np.zeros((16,16)), sig(ek)],[sigt(ek), np.zeros((16,16))]]))
res['32x32 gammas: {g_a,g_b} = 2 delta_ab'] = all(np.allclose(gam[a]@gam[b]+gam[b]@gam[a], 2*(a==b)*np.eye(32)) for a in range(10) for b in range(10))
# Pati--Salam split: R^4 = (v0, v9, 1, e7)  [complex slice C_I plus the two extra directions], R^6 = (e1..e6) = C_I^perp
# coordinate index: v0 -> 0, octonion e_j -> j+1, v9 -> 9
pairs = [(2,3),(4,5),(6,7),(0,9),(1,8)]   # (e1,e2),(e3,e4),(e5,e6) colour-like ; (v0,v9),(1,e7)
H = [0.5j*gam[p]@gam[q] for p,q in pairs]   # Hermitian? (i/2)gamma_p gamma_q, eigenvalues +-1/2
